def _cut_layer(content: str, header: str) -> str:
    """把某一层整段切掉：从它的标题切到下一个「【…】」层标题之前。

    为什么不用 str.replace：表情层的正文以后可能被改，写死整段文本会脆。
    按层标题切，层序不变，缺标题时原样返回（不抛异常）。
    """
    start = content.find(header)
    if start < 0:
        return content
    nxt = content.find("\n【", start + len(header))
    if nxt < 0:
        return content[:start].rstrip() + "\n"
    return content[:start] + content[nxt + 1 :]


def attach(
    messages: list[dict[str, Any]],
    *,
    emoji: bool = False,
    examples: bool = True,
    wit: bool = True,
    tsundere: bool = True,
    shape: bool = True,
    target_sample: bool = True,
    segment_override: bool = True,
) -> list[dict[str, Any]]:
    """把演出层（+土话矫正+傲娇语感+固定形状+目标样例+范例，可选禁表情包）插进 Prompt。

    :param emoji: True = 保留共享的表情层；False（默认，用户 2026-10-04 要求）
        把表情层整段换成「不用表情包、情绪走演出层」。
    :param examples: 是否附带形状范例（模仿范例是提水平最有效的一招）。
    :param wit: 是否附带「土与不土」层（用户 2026-10-04：「说话太土了」）。
    :param tsundere: 是否附带傲娇语感层（软下来三招 + 每句加料 + 自夸词库方向）。
    :param shape: 是否附带**固定形状层**（用户 2026-10-04：「只有说白饭的时候才有那种感觉，
        说其他又成土狗了」→ 把"形状"钉死，并给跨话题示范，免得模型只会照抄例子内容）。
    :param target_sample: 是否附带**目标样例**（用户反复贴的那段同行输出，
        用来对齐"信息密度"：四句台词要塞进否认/身份/歪理/事实/金句）。
    :param segment_override: 是否推翻任务层「默认只发 1 条」的段数限制。

    只处理本项目的单条 user 消息格式；消息多于一条（例如已经附了图片的
    多模态消息）时，改**最后一条**，位置规则一样。返回新对象，不改原 messages
    （dispatcher 里它后面还要被 `vision.attach_image` 用）。
    """
    if not messages:
        return messages
    out = [dict(m) for m in messages]
    last = out[-1]
    content = str(last.get("content") or "")

    if not emoji:
        # 表情层整段换成「不用表情包」的说明，位置不变（还在原处，层序不乱）。
        if EMOJI_LAYER_HEADER in content:
            content = _cut_layer(content, EMOJI_LAYER_HEADER)
            idx_after = content.find("\n【")
            note = NO_EMOJI_NOTE + "\n"
            if idx_after < 0:
                content = content.rstrip() + "\n\n" + NO_EMOJI_NOTE + "\n"
            else:
                content = content[:idx_after] + "\n" + note + content[idx_after:].lstrip("\n")
        else:
            content = content.rstrip() + "\n\n" + NO_EMOJI_NOTE + "\n"

    blocks = [PERFORMANCE_PROMPT]
    if wit:
        blocks.append(WIT_PROMPT)
    if tsundere:
        blocks.append(TSUNDERE_PROMPT)
    if shape:
        blocks.append(SHAPE_RECIPE)
    if target_sample:
        blocks.append(TARGET_SAMPLE)
    if examples:
        blocks.append(STYLE_EXAMPLES)
    if segment_override:
        blocks.append(SEGMENT_OVERRIDE)
    block = "\n\n".join(blocks) + "\n\n"

    idx = content.find(TASK_LAYER_MARKER)
    if idx < 0:
        content = content + ("\n\n" if content else "") + block.rstrip()
    else:
        content = content[:idx] + block + content[idx:]

    last["content"] = content
    return out
